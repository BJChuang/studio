import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { localizeAssetPaths, normalizeBasePath } from './base-path.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'dist');
const args = process.argv.slice(2);
const baseIndex = args.indexOf('--base');
if (baseIndex >= 0 && !args[baseIndex + 1]) throw new Error('Missing --base value');
const basePath = normalizeBasePath(baseIndex >= 0 ? args[baseIndex + 1] : '/');
await mkdir(output, { recursive: true });
for (const entry of ['index.html', 'favicon.svg', 'src', 'creator-prototype', 'provenance.json']) {
  await cp(resolve(root, entry), resolve(output, entry), { recursive: true });
}
for (const entry of ['src/main.js', 'src/prototypeSurface.js', 'src/generated/initializePrototype.js', 'src/generated/markup.js']) {
  const source = await readFile(resolve(root, entry), 'utf8');
  await writeFile(resolve(output, entry), localizeAssetPaths(source, basePath));
}
const generated = resolve(output, 'src/generated');
// Remove only bundle files generated by this script, never source or media.
for (const name of await readdir(generated)) {
  if (/^studio-(runtime|markup)-[a-f0-9]{16}-\d{3}\.bin$/.test(name)) await rm(resolve(generated, name));
}
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const manifest = { version: 1, modules: [] };
for (const [name, file] of [['runtime', 'initializePrototype.js'], ['markup', 'markup.js']]) {
  const bytes = await readFile(resolve(generated, file));
  const compressed = gzipSync(bytes, { level: 9 });
  const module = { name, bytes: bytes.length, sha256: sha256(bytes), parts: [] };
  for (let start = 0; start < compressed.length; start += 256 * 1024) {
    const part = compressed.subarray(start, start + 256 * 1024);
    const hash = sha256(part);
    const partFile = `studio-${name}-${hash.slice(0, 16)}-${String(module.parts.length).padStart(3, '0')}.bin`;
    await writeFile(resolve(generated, partFile), part);
    module.parts.push({ file: partFile, bytes: part.length, sha256: hash });
  }
  manifest.modules.push(module);
}
const manifestText = `${JSON.stringify(manifest)}\n`;
await writeFile(resolve(generated, 'bundles.json'), manifestText);
// The small bootstrap is one module, avoiding an extra request waterfall before
// the large, independently retryable program download can begin.
const entry = [
  await readFile(resolve(output, 'src/prototypeSurface.js'), 'utf8'),
  await readFile(resolve(root, 'src/moduleLoader.js'), 'utf8'),
  (await readFile(resolve(output, 'src/main.js'), 'utf8')).replace(/^import [^\n]+;\r?\n/gm, ''),
].join('\n');
await writeFile(resolve(output, 'src/entry.js'), entry);
const bundleURL = `./src/generated/bundles.json?v=${sha256(manifestText).slice(0, 16)}`;
const entryURL = `./src/entry.js?v=${sha256(entry).slice(0, 16)}`;
const html = await readFile(resolve(root, 'index.html'), 'utf8');
await writeFile(resolve(output, 'index.html'), html
  .replace('./src/main.js', entryURL)
  .replace('</head>', `  <meta name="studio-bundles" content="${bundleURL}">\n    <link rel="modulepreload" href="${entryURL}">\n    <link rel="preload" href="${bundleURL}" as="fetch" crossorigin>\n  </head>`));
await writeFile(resolve(output, '.nojekyll'), '');
await writeFile(resolve(output, 'site-config.json'), `${JSON.stringify({ basePath }, null, 2)}\n`);
console.log(`Static files ready: ${output}`);
console.log(`Deployment base path: ${basePath}`);
console.log(`Startup download: ${manifest.modules.reduce((sum, module) => sum + module.parts.reduce((total, part) => total + part.bytes, 0), 0).toLocaleString('en-US')} bytes in ${manifest.modules.flatMap(module => module.parts).length} retryable chunks.`);
